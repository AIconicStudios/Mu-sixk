/* Mu-sixk key finder.
   1. Downsample to ~22 kHz and take long FFTs (2.7 Hz detail) so low notes land on the right semitone.
   2. Pick spectral peaks against a smoothed envelope (so timbre and drums matter less).
   3. Measure the recording's tuning (A = 440 Hz or not) from where the peaks sit between semitones.
   4. Build a pitch-class profile, crediting each peak to the notes it could be an overtone of.
   5. Build a separate bass profile: the bass usually lands on the home note.
   6. Score all 24 keys against key templates; confidence is calibrated on labelled songs.
   Templates and calibration live in src/keyprofiles.js (generated by tools/keybench.js). */
(function (root) {
  'use strict';
  const M = (root.MuSixk = root.MuSixk || {});
  const { fft, hann } = M.dsp;

  const NOTES = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B'];
  const FLATS = ['C', 'Db', 'D', 'Eb', 'E', 'F', 'Gb', 'G', 'Ab', 'A', 'Bb', 'B'];
  /* Keys conventionally written with flats. */
  const FLAT_KEYS = { major: [1, 3, 5, 8, 10], minor: [0, 2, 5, 7, 10, 3] };
  const CAMELOT_MAJOR = [8, 3, 10, 5, 12, 7, 2, 9, 4, 11, 6, 1]; // B-side number by tonic
  const SCALES = { major: [0, 2, 4, 5, 7, 9, 11], minor: [0, 2, 3, 5, 7, 8, 10] };

  /* Published templates (major, minor; tonic first), used as fallbacks and for comparison. */
  const PUBLISHED = {
    krumhansl: [[6.35, 2.23, 3.48, 2.33, 4.38, 4.09, 2.52, 5.19, 2.39, 3.66, 2.29, 2.88], [6.33, 2.68, 3.52, 5.38, 2.6, 3.53, 2.54, 4.75, 3.98, 2.69, 3.34, 3.17]],
    temperley: [[0.748, 0.06, 0.488, 0.082, 0.67, 0.46, 0.096, 0.715, 0.104, 0.366, 0.057, 0.4], [0.712, 0.084, 0.474, 0.618, 0.049, 0.46, 0.105, 0.747, 0.404, 0.067, 0.133, 0.33]],
    shaath: [[7.24, 3.5, 3.58, 2.84, 5.38, 4.21, 2.52, 6.1, 3.18, 4.4, 2.66, 3.47], [7.0, 3.14, 4.36, 5.4, 3.67, 4.08, 3.91, 6.2, 3.63, 2.87, 5.35, 3.83]],
    albrecht: [[0.238, 0.006, 0.111, 0.006, 0.137, 0.094, 0.016, 0.214, 0.009, 0.08, 0.008, 0.081], [0.22, 0.006, 0.104, 0.123, 0.019, 0.103, 0.012, 0.214, 0.062, 0.022, 0.061, 0.052]],
  };
  const DEFAULTS = { harmonics: 4, decay: 0.6, weight: 'sqrt', bassWeight: 0.5, low: 80, high: 5000, profile: 'learned' };

  /* ---------- signal preparation ---------- */
  function lowpassTaps(cutoff, n) {
    const taps = new Float64Array(n), mid = (n - 1) / 2;
    let sum = 0;
    for (let i = 0; i < n; i++) {
      const t = i - mid;
      const sinc = t === 0 ? 2 * cutoff : Math.sin(2 * Math.PI * cutoff * t) / (Math.PI * t);
      const w = 0.42 - 0.5 * Math.cos((2 * Math.PI * i) / (n - 1)) + 0.08 * Math.cos((4 * Math.PI * i) / (n - 1));
      taps[i] = sinc * w; sum += taps[i];
    }
    for (let i = 0; i < n; i++) taps[i] /= sum;
    return taps;
  }
  /* Mono mix, low-passed and downsampled until the rate is under 30 kHz. */
  function prepare(channels, fs) {
    const n = channels[0].length;
    let x = new Float32Array(n);
    for (const ch of channels) for (let i = 0; i < n; i++) x[i] += ch[i] / channels.length;
    let rate = fs;
    const taps = lowpassTaps(0.22, 47);
    while (rate > 30000) {
      const m = Math.floor(x.length / 2), y = new Float32Array(m);
      for (let j = 0; j < m; j++) {
        let s = 0;
        const c = 2 * j;
        for (let k = 0; k < taps.length; k++) { const idx = c + k - 23; if (idx >= 0 && idx < x.length) s += taps[k] * x[idx]; }
        y[j] = s;
      }
      x = y; rate /= 2;
    }
    return { x, rate };
  }

  /* ---------- spectral peaks ---------- */
  function framePeaks(x, rate, opts) {
    const N = rate > 16000 ? 8192 : 4096;
    const hop = N / 2;
    const win = hann(N);
    const re = new Float64Array(N), im = new Float64Array(N), mag = new Float64Array(N / 2), pre = new Float64Array(N / 2 + 1);
    const df = rate / N;
    const kLo = Math.max(2, Math.floor(30 / df)), kHi = Math.min(N / 2 - 2, Math.ceil(opts.high / df));
    const total = Math.max(1, Math.floor((x.length - N) / hop) + 1);
    const step = Math.max(1, Math.ceil(total / (opts.maxFrames || 2400)));
    const frames = [];
    for (let f = 0; f < total; f += step) {
      const start = f * hop;
      let energy = 0;
      for (let i = 0; i < N; i++) { const v = start + i < x.length ? x[start + i] : 0; re[i] = v * win[i]; im[i] = 0; energy += v * v; }
      if (energy / N < 1e-8) { frames.push({ t: (start + N / 2) / rate, peaks: [] }); continue; }
      fft(re, im);
      let max = 0;
      for (let k = 0; k < N / 2; k++) { mag[k] = Math.sqrt(re[k] * re[k] + im[k] * im[k]); if (k >= kLo && k <= kHi && mag[k] > max) max = mag[k]; }
      pre[0] = 0;
      for (let k = 0; k < N / 2; k++) pre[k + 1] = pre[k] + mag[k];
      const floor = max * 1e-3;
      const peaks = [];
      for (let k = kLo; k <= kHi; k++) {
        const m = mag[k];
        if (m < floor || m <= mag[k - 1] || m < mag[k + 1]) continue;
        const w = Math.max(3, Math.round(k * 0.08));
        const a = Math.max(0, k - w), b = Math.min(N / 2, k + w + 1);
        const env = (pre[b] - pre[a]) / (b - a);
        if (m < (opts.peakRatio || 1.6) * env) continue;
        const l1 = Math.log(mag[k - 1] + 1e-12), l2 = Math.log(m + 1e-12), l3 = Math.log(mag[k + 1] + 1e-12);
        const d = l1 - 2 * l2 + l3;
        const shift = d < 0 ? Math.max(-0.5, Math.min(0.5, (0.5 * (l1 - l3)) / d)) : 0;
        peaks.push({ f: (k + shift) * df, a: m / max, s: m / env });
      }
      frames.push({ t: (start + N / 2) / rate, peaks });
    }
    return frames;
  }

  /* Tuning offset in cents (-50..50): circular mean of where peaks sit between semitones. */
  function tuning(frames) {
    let c = 0, s = 0;
    for (const fr of frames) for (const p of fr.peaks) {
      if (p.f < 100 || p.f > 2500) continue;
      const midi = 69 + 12 * Math.log2(p.f / 440);
      const ang = 2 * Math.PI * (midi - Math.round(midi));
      const w = Math.sqrt(p.a);
      c += w * Math.cos(ang); s += w * Math.sin(ang);
    }
    return c === 0 && s === 0 ? 0 : (100 * Math.atan2(s, c)) / (2 * Math.PI);
  }

  /* ---------- pitch-class profiles ---------- */
  function addPc(chroma, f, ref, w) {
    const pitch = 12 * Math.log2(f / ref);
    const pc = ((pitch % 12) + 12) % 12;
    const lo = Math.floor(pc), frac = pc - lo;
    chroma[lo % 12] += w * Math.cos((frac * Math.PI) / 2) ** 2;
    chroma[(lo + 1) % 12] += w * Math.sin((frac * Math.PI) / 2) ** 2;
  }
  const weightOf = (p, how) => (how === 'lin' ? p.a : how === 'whiten' ? Math.log(p.s) : Math.sqrt(p.a));

  function frameChroma(fr, ref, opts) {
    const chroma = new Float64Array(12), bass = new Float64Array(12);
    for (const p of fr.peaks) {
      const w = weightOf(p, opts.weight);
      if (p.f >= opts.low && p.f <= opts.high) {
        for (let h = 1; h <= opts.harmonics; h++) {
          const f0 = p.f / h;
          if (f0 < 40) break;
          addPc(chroma, f0, ref, w * Math.pow(opts.decay, h - 1));
        }
      }
      if (p.f >= 30 && p.f <= 250) addPc(bass, p.f, ref, w);
    }
    return { chroma, bass };
  }

  function normalise(v) {
    let m = 0;
    for (const x of v) if (x > m) m = x;
    return m > 0 ? Array.from(v, (x) => x / m) : Array.from(v);
  }

  function corr(a, b) {
    const n = a.length;
    let ma = 0, mb = 0;
    for (let i = 0; i < n; i++) { ma += a[i]; mb += b[i]; }
    ma /= n; mb /= n;
    let num = 0, da = 0, db = 0;
    for (let i = 0; i < n; i++) { num += (a[i] - ma) * (b[i] - mb); da += (a[i] - ma) ** 2; db += (b[i] - mb) ** 2; }
    return da > 0 && db > 0 ? num / Math.sqrt(da * db) : 0;
  }

  function templates(opts) {
    const learned = M.keyProfiles;
    if (opts.profile === 'learned' && learned) return { major: learned.major, minor: learned.minor, bassMajor: learned.bassMajor, bassMinor: learned.bassMinor };
    const [major, minor] = PUBLISHED[opts.profile === 'learned' ? 'temperley' : opts.profile];
    return { major, minor, bassMajor: major, bassMinor: minor };
  }

  /* Scores for all 24 keys from a chroma and a bass chroma. */
  function scoreKeys(chroma, bass, opts) {
    const T = templates(opts);
    const out = [];
    for (let tonic = 0; tonic < 12; tonic++) {
      const rc = chroma.map((_, i) => chroma[(i + tonic) % 12]);
      const rb = bass.map((_, i) => bass[(i + tonic) % 12]);
      for (const mode of ['major', 'minor']) {
        const main = corr(rc, T[mode]);
        const low = bass.some((v) => v > 0) ? corr(rb, mode === 'major' ? T.bassMajor : T.bassMinor) : 0;
        out.push({ tonic, mode, score: main + opts.bassWeight * low });
      }
    }
    return out.sort((a, b) => b.score - a.score);
  }

  /* ---------- naming and music theory helpers ---------- */
  function keyName(tonic, mode) {
    const flat = FLAT_KEYS[mode].includes(tonic);
    return `${(flat ? FLATS : NOTES)[tonic]} ${mode}`;
  }
  const noteName = (pc, tonic, mode) => (FLAT_KEYS[mode].includes(tonic) ? FLATS : NOTES)[((pc % 12) + 12) % 12];
  function camelot(tonic, mode) {
    if (mode === 'major') return `${CAMELOT_MAJOR[tonic]}B`;
    return `${CAMELOT_MAJOR[(tonic + 3) % 12]}A`;
  }
  function chords(tonic, mode) {
    const scale = SCALES[mode].map((s) => (s + tonic) % 12);
    const qual = mode === 'major' ? ['', 'm', 'm', '', '', 'm', 'dim'] : ['m', 'dim', '', 'm', 'm', '', ''];
    const roman = mode === 'major' ? ['I', 'ii', 'iii', 'IV', 'V', 'vi', 'vii°'] : ['i', 'ii°', 'III', 'iv', 'v', 'VI', 'VII'];
    const list = scale.map((pc, i) => ({ roman: roman[i], name: noteName(pc, tonic, mode) + qual[i] }));
    if (mode === 'minor') list.push({ roman: 'V (harmonic)', name: noteName(scale[4], tonic, mode) });
    return list;
  }
  function related(tonic, mode) {
    const rel = mode === 'major' ? [(tonic + 9) % 12, 'minor'] : [(tonic + 3) % 12, 'major'];
    return {
      relative: keyName(...rel),
      parallel: keyName(tonic, mode === 'major' ? 'minor' : 'major'),
      mixesWith: [[(tonic + 7) % 12, mode], [(tonic + 5) % 12, mode], rel].map(([t, m]) => `${camelot(t, m)} ${keyName(t, m)}`),
    };
  }

  /* Probability-like confidence from the score gap, with a temperature fitted on labelled songs and softened for
     short clips (fitted on held-out songs: x1.3 at 60 s rising to x2.3 at 7 s). */
  function confidences(ranked, seconds = 60, baseTemp) {
    const base = baseTemp || (M.keyProfiles && M.keyProfiles.temperature) || 0.05;
    const temp = base * 1.3 * Math.pow(60 / Math.max(5, Math.min(60, seconds)), 0.23);
    const top = ranked[0].score;
    const exps = ranked.map((r) => Math.exp((r.score - top) / temp));
    const sum = exps.reduce((a, b) => a + b, 0);
    return ranked.map((r, i) => ({ ...r, p: exps[i] / sum }));
  }

  function describe(ranked) {
    const best = ranked[0];
    const name = keyName(best.tonic, best.mode);
    return {
      tonic: best.tonic, mode: best.mode, name, camelot: camelot(best.tonic, best.mode), confidence: best.p,
      scale: SCALES[best.mode].map((s) => noteName(s + best.tonic, best.tonic, best.mode)),
      scalePcs: SCALES[best.mode].map((s) => (s + best.tonic) % 12),
      chords: chords(best.tonic, best.mode), ...related(best.tonic, best.mode),
      alternatives: ranked.slice(1, 4).map((r) => ({ name: keyName(r.tonic, r.mode), camelot: camelot(r.tonic, r.mode), p: r.p })),
    };
  }

  /* Main entry: channels (Float32Array[]) and sample rate. */
  function detect(channels, fs, options = {}) {
    const opts = { ...DEFAULTS, ...((M.keyProfiles && M.keyProfiles.settings) || {}), ...options };
    const { x, rate } = prepare(channels, fs);
    const frames = framePeaks(x, rate, opts);
    const cents = tuning(frames);
    const ref = 440 * Math.pow(2, cents / 1200) / Math.pow(2, 9 / 12); // tuned C
    const chroma = new Float64Array(12), bass = new Float64Array(12);
    const perFrame = frames.map((fr) => {
      const fc = frameChroma(fr, ref, opts);
      const cm = Math.max(...fc.chroma), bm = Math.max(...fc.bass);
      /* Optionally weight each frame by how tonal it is, so drum hits and breaths count for less. */
      let fw = 1;
      if (opts.frameGate && cm > 0) {
        const mean = fc.chroma.reduce((s, v) => s + v, 0) / 12;
        const sd = Math.sqrt(fc.chroma.reduce((s, v) => s + (v - mean) ** 2, 0) / 12);
        fw = Math.max(0, Math.min(1, (sd / (mean || 1) - 0.3) / 0.6));
      }
      if (cm > 0) for (let i = 0; i < 12; i++) chroma[i] += (fw * fc.chroma[i]) / cm;
      if (bm > 0) for (let i = 0; i < 12; i++) bass[i] += fc.bass[i] / bm;
      return { t: fr.t, chroma: cm > 0 ? fc.chroma.map((v) => v / cm) : fc.chroma, bass: bm > 0 ? fc.bass.map((v) => v / bm) : fc.bass };
    });
    if (!chroma.some((v) => v > 0)) return null;
    const c = normalise(chroma), b = normalise(bass);
    /* How tonal the sound is: drums and noise spread evenly over all 12 notes (about 0.1), music does not (0.4+). */
    const mean = c.reduce((s, v) => s + v, 0) / 12;
    const spread = Math.sqrt(c.reduce((s, v) => s + (v - mean) ** 2, 0) / 12) / (mean || 1);
    const tonal = Math.max(0, Math.min(1, (spread - 0.18) / (0.35 - 0.18)));
    const seconds = x.length / rate;
    const ranked = confidences(scoreKeys(c, b, opts), seconds).map((r) => ({ ...r, p: r.p * tonal }));
    const result = describe(ranked);
    result.tonal = tonal;
    result.seconds = seconds;
    result.noKey = tonal < 0.3;
    result.tuningCents = cents;
    result.referenceA = 440 * Math.pow(2, cents / 1200);
    result.chroma = c;
    result.bass = b;
    result.ranked = ranked;
    result.timeline = timeline(perFrame, opts, result);
    return result;
  }

  /* Key in overlapping windows; a change is only reported when it holds for two windows in a row. */
  function timeline(perFrame, opts, global) {
    if (!perFrame.length) return [];
    const dur = perFrame[perFrame.length - 1].t;
    if (dur < 50) return [{ start: 0, end: dur, name: global.name, camelot: global.camelot }];
    const win = 24, hop = 12;
    const raw = [];
    for (let s = 0; s + win / 2 < dur; s += hop) {
      const inside = perFrame.filter((f) => f.t >= s && f.t < s + win);
      if (inside.length < 10) continue;
      const c = new Array(12).fill(0), b = new Array(12).fill(0);
      inside.forEach((f) => { for (let i = 0; i < 12; i++) { c[i] += f.chroma[i]; b[i] += f.bass[i]; } });
      if (!c.some((v) => v > 0)) continue;
      const r = confidences(scoreKeys(normalise(c), normalise(b), opts), win)[0];
      raw.push({ start: s, end: Math.min(dur, s + win), tonic: r.tonic, mode: r.mode, p: r.p });
    }
    const same = (a, k) => a.tonic === k.tonic && a.mode === k.mode;
    const out = [];
    raw.forEach((w, i) => {
      const steady = same(w, global) || (raw[i + 1] && same(raw[i + 1], w)) || (raw[i - 1] && same(raw[i - 1], w));
      const k = steady ? w : { tonic: global.tonic, mode: global.mode };
      const last = out[out.length - 1];
      if (last && last.tonic === k.tonic && last.mode === k.mode) last.end = w.end;
      else out.push({ start: last ? last.end : 0, end: w.end, tonic: k.tonic, mode: k.mode });
    });
    if (out.length) out[out.length - 1].end = dur;
    return out.map((o) => ({ start: o.start, end: o.end, name: keyName(o.tonic, o.mode), camelot: camelot(o.tonic, o.mode) }));
  }

  M.key = { detect, keyName, camelot, chords, NOTES, FLATS, PUBLISHED, DEFAULTS, SCALES, _internal: { prepare, framePeaks, tuning, frameChroma, scoreKeys, normalise, corr, confidences, describe } };
})(typeof self !== 'undefined' ? self : globalThis);
